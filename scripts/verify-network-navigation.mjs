import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from '../EnsuredNetwork/node_modules/playwright/index.mjs';
import { expect } from '../EnsuredNetwork/node_modules/@playwright/test/index.mjs';
const {accounts}=JSON.parse(await readFile(new URL('../output/network-seed/v1/credentials.json',import.meta.url),'utf8'));
const browser=await chromium.launch({headless:true});
try {
 const context=await browser.newContext({viewport:{width:1440,height:1100}}),page=await context.newPage();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const account=accounts.find(a=>a.key==='cedent');
 const login=await context.request.post('http://localhost:3000/identity/sign-in/email',{headers:{Origin:'http://localhost:3000'},data:{email:account.email,password:account.password}});
 expect(login.ok()).toBeTruthy();
 await page.goto('http://localhost:3000/network/explore');
 const nav=page.locator('#application-sidebar');
 await expect(nav.getByRole('link',{name:'Discover',exact:true})).toBeVisible();
 await expect(nav.getByRole('button',{name:'My Network',exact:true})).toBeVisible();
 await expect(nav.getByRole('button',{name:'Find Capacity',exact:true})).toBeVisible();
 await expect(nav.getByRole('button',{name:'Manage Business',exact:true})).toHaveAttribute('aria-expanded','false');
 await nav.getByRole('button',{name:'My Network',exact:true}).click();
 await expect(nav.getByRole('link',{name:/Introductions/})).toBeVisible();
 const counts=await (await context.request.get('http://localhost:3000/api/network/navigation')).json();
 if(counts.pendingIntroductions>0) await expect(nav.getByRole('link',{name:/Introductions/})).toContainText(`${counts.pendingIntroductions} pending`);
 await nav.getByRole('button',{name:'Relationships & Agreements',exact:true}).click();
 await expect(nav.getByRole('link',{name:'Agreements',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'Find Capacity',exact:true}).click();
 await nav.getByRole('link',{name:'Find Capacity',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Find Capacity',exact:true})).toBeVisible();
 await expect(nav.getByRole('link',{name:'Find Capacity',exact:true})).toHaveAttribute('aria-current','page');
 await page.goto('http://localhost:3000/network/commitments');
 await expect(nav.getByRole('button',{name:'Manage Business',exact:true})).toHaveAttribute('aria-expanded','true');
 await expect(nav.getByRole('button',{name:'Facilities & Commitments',exact:true})).toHaveAttribute('aria-expanded','true');
 await expect(nav.getByRole('link',{name:'Commitments',exact:true})).toHaveAttribute('aria-current','page');
 await page.goto('http://localhost:3000/network/reinsurance');
 await expect(page.getByRole('heading',{name:'Placements',exact:true})).toBeVisible();
 await expect(nav.getByRole('link',{name:'Retrocession',exact:true})).toBeVisible();
 await page.goto('http://localhost:3000/network');
 await expect(page.getByRole('heading',{name:'Market Feed',exact:true})).toBeVisible();
 await page.goto('http://localhost:3000/network/explore');
 await expect(page.getByRole('heading',{name:'Find the right opportunities'})).toBeVisible();
 await mkdir(new URL('../output/network-navigation/',import.meta.url),{recursive:true});
 await page.screenshot({path:new URL('../output/network-navigation/desktop.png',import.meta.url).pathname,fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation menu'}).click();
 await expect(nav.getByRole('link',{name:'Discover',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'Personal',exact:true}).click();
 await expect(nav.getByRole('link',{name:'My Profile',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(nav).toBeHidden();
 expect(errors).toEqual([]);
 console.log('Navigation verified: primary journeys, collapsible groups, deep-link expansion, introduction counts, distinct capacity pages, titles and mobile menu.');
} finally {await browser.close();}
