import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from '../EnsuredNetwork/node_modules/playwright/index.mjs';
import { expect } from '../EnsuredNetwork/node_modules/@playwright/test/index.mjs';
const accounts = JSON.parse(await readFile(new URL('../output/network-seed/v1/credentials.json', import.meta.url), 'utf8')).accounts;
const account = accounts.find(a => a.key === 'reinsurer');
const browser = await chromium.launch({headless:true});
try {
  const context = await browser.newContext({viewport:{width:1440,height:1100}});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const login = await context.request.post('http://localhost:3000/identity/sign-in/email',{headers:{Origin:'http://localhost:3000'},data:{email:account.email,password:account.password}});
  expect(login.ok()).toBeTruthy();
  await page.goto('http://localhost:3000/network/explore');
  await expect(page.getByRole('heading',{name:'Find the right opportunities'})).toBeVisible();
  await expect(page.locator('.en-discover-card').first()).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByLabel('Capacity Type',{exact:true}).selectOption('Broker');
  await expect(page.locator('.en-discover-card')).toHaveCount(1);
  await expect(page.locator('.en-discover-card')).toContainText('Daniel Okoro');
  await expect(page.locator('.en-discover-card')).toContainText('15+ years experience');
  await page.getByRole('button',{name:'Connect',exact:false}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'Clear filters',exact:true}).first().click();
  await expect(page.locator('.en-discover-card').first()).toBeVisible();
  await mkdir(new URL('../output/network-discovery/',import.meta.url),{recursive:true});
  await page.screenshot({path:new URL('../output/network-discovery/desktop.png',import.meta.url).pathname,fullPage:true});
  await page.getByLabel('Only show open opportunities').click();
  await expect(page.getByLabel('Only show open opportunities')).toBeChecked();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByRole('button',{name:'Organizations',exact:true}).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Posts',exact:true})).toHaveCount(0);
  await page.goto('http://localhost:3000/network/explore?type=posts');
  await expect(page.locator('.en-discover-card').first()).toBeVisible();
  await expect(page.locator('.en-post')).toHaveCount(0);
  await page.goto('http://localhost:3000/network/explore');
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.en-discover-card').first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({path:new URL('../output/network-discovery/mobile.png',import.meta.url).pathname,fullPage:true});
  expect(errors).toEqual([]);
  console.log('Discovery verified: live profiles, filters, introduction dialog, categories, desktop and mobile.');
} finally { await browser.close(); }
